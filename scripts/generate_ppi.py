def parse_ym(s):
    y, m = s.split('-')
    return int(y), int(m)


def ym_key(y, m):
    return f'{y:04d}-{m:02d}'


def generate_all_months(start='1947-01', end='2025-05'):
    months = []
    sy, sm = parse_ym(start)
    ey, em = parse_ym(end)
    y, m = sy, sm
    while (y, m) <= (ey, em):
        months.append(ym_key(y, m))
        m += 1
        if m > 12:
            m = 1
            y += 1
    return months


def fill_interpolated(known, months):
    filled = dict(known)
    for i, k in enumerate(months):
        if k in filled:
            continue
        prev_k = next_k = None
        for j in range(i - 1, -1, -1):
            if months[j] in filled:
                prev_k = months[j]
                break
        for j in range(i + 1, len(months)):
            if months[j] in filled:
                next_k = months[j]
                break
        if prev_k and next_k:
            py, pm = parse_ym(prev_k)
            ny, nm = parse_ym(next_k)
            ky, km = parse_ym(k)
            total = (ny - py) * 12 + (nm - pm)
            step = (ky - py) * 12 + (km - pm)
            filled[k] = round(filled[prev_k] + (filled[next_k] - filled[prev_k]) * step / total, 1)
    return filled


def main():
    months = generate_all_months()
    filled = fill_interpolated(PPI_KNOWN, months)

    Path('assets/data/macro').mkdir(parents=True, exist_ok=True)
    out_path = Path('assets/data/macro/PPI.csv')
    with open(out_path, 'w', newline='') as f:
        w = csv.writer(f)
        w.writerow(['date', 'ppi'])
        for k in months:
            if k in filled:
                y, mo = k.split('-')
                w.writerow([f'{y}-{mo}-01', filled[k]])

    print(f'Written {len([k for k in months if k in filled])} rows to {out_path}')


if __name__ == '__main__':
    main()
